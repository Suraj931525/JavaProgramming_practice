package Basicprogram;

public class operator {

	public static void main(String[] args) {
		
		// Arithmetic operator
        System.out.println("Addition:"+ (4+6));
        System.out.println("substraction:"+ (4-6));
        System.out.println("multiplication:"+ (4*6));
        System.out.println("Division:"+ (4/6));
        System.out.println("modulus:"+ (4%6));
        
        
        
        //comparision operator
        System.out.println("Comparison operator");

        System.out.println("Equal to: " + (6 == 7));
        System.out.println("Not equal to: " + (6 != 7));
        System.out.println("Greater than: " + (6 > 7));
        System.out.println("Less than: " + (6 < 7));

        System.out.println("Greater than or equal to: " + (6 >= 7));
        System.out.println("Less than or equal to: " + (6 <= 7));
       
        
       

	}

}
